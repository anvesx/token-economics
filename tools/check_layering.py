"""Layering check: a package imports only the packages in its `deps` (plan/13-monorepo-layout.md, rules 1 and 3).

    uv run python tools/check_layering.py
    uv run python tools/check_layering.py --write-importlinter    # also (re)generate .importlinter

Reads every .py file under each existing package's src/ and tests/ with `ast`, so nothing needs to be installed.
Rules: no sibling or higher-kind imports, no undeclared workspace imports, no other package's private modules
(`_internal`, or any module or name starting with `_`). Tests may also import contracts' `testing` module.
Exits 1 and prints one line per problem.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

from _layout import KIND_ORDER, ROOT, Layout, existing, load_layout, module_name

TESTING_MODULE = "token_economics_contracts.testing"


def _is_private(part: str) -> bool:
    return part.startswith("_") and not (part.startswith("__") and part.endswith("__"))


def _imports(tree: ast.AST) -> list[tuple[int, str, list[str]]]:
    """(line, dotted module, imported names) for every absolute import."""
    found: list[tuple[int, str, list[str]]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.extend((node.lineno, a.name, []) for a in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            found.append((node.lineno, node.module, [a.name for a in node.names]))
    return found


def check_file(layout: Layout, key: str, path: Path, rel: str, in_tests: bool) -> list[str]:
    by_module = {module_name(k): k for k in layout}
    deps = set(layout[key]["deps"])
    kind = KIND_ORDER.index(layout[key]["kind"])
    try:
        tree = ast.parse(path.read_text(), filename=str(path))
    except SyntaxError as exc:
        return [f"{rel}:{exc.lineno}: cannot parse ({exc.msg})"]
    problems: list[str] = []
    for line, dotted, names in _imports(tree):
        root_mod, *rest = dotted.split(".")
        if not root_mod.startswith("token_economics_"):
            continue  # stdlib or third party
        target = by_module.get(root_mod)
        if target is None:
            problems.append(f"{rel}:{line}: imports {dotted}, which is not a package in layout.json")
            continue
        if target == key:
            continue
        if in_tests and (dotted == TESTING_MODULE or dotted.startswith(TESTING_MODULE + ".")):
            continue
        if target not in deps:
            if KIND_ORDER.index(layout[target]["kind"]) >= kind:
                why = "a sibling or higher kind"
            else:
                why = "a lower kind that is not declared in deps"
            problems.append(f"{rel}:{line}: {key} imports {dotted} ({why}; allowed: {sorted(deps) or 'nothing'})")
            continue
        private = [p for p in rest if _is_private(p)]
        if not rest:
            private += [n for n in names if _is_private(n)]
        if private:
            problems.append(f"{rel}:{line}: {key} imports private {private[0]} of {target} ({dotted})")
    return problems


def check(layout: Layout, root: Path = ROOT) -> list[str]:
    problems: list[str] = []
    for key in existing(layout, root):
        pkg = root / layout[key]["dir"]
        for sub in ("src", "tests"):
            for path in sorted((pkg / sub).rglob("*.py")):
                rel = path.relative_to(root).as_posix()
                problems += check_file(layout, key, path, rel, in_tests=(sub == "tests"))
    return problems


def _private_modules(layout: Layout, key: str, root: Path) -> list[str]:
    """Dotted names of the private modules and sub-packages that exist in a package."""
    base = root / layout[key]["dir"] / "src"
    out: list[str] = []
    for path in sorted(base.rglob("*")):
        if path.suffix not in ("", ".py") or path.name == "__pycache__":
            continue
        rel = path.relative_to(base)
        parts = list(rel.with_suffix("").parts)
        if any(_is_private(p) for p in parts):
            # only the outermost private module needs forbidding; its children are covered by it
            first = next(i for i, p in enumerate(parts) if _is_private(p))
            dotted = ".".join(parts[: first + 1])
            if dotted not in out:
                out.append(dotted)
    return out


def importlinter_config(layout: Layout, root: Path = ROOT) -> str:
    keys = existing(layout, root)
    mods = {k: module_name(k) for k in keys}
    lines = [
        "# Generated by `uv run python tools/check_layering.py --write-importlinter` from plan/model/layout.json.",
        "# Do not edit by hand. Only packages whose folder exists are listed; regenerate after adding one.",
        "",
        "[importlinter]",
        "root_packages =",
        *[f"    {mods[k]}" for k in keys],
        "",
        "[importlinter:contract:kinds]",
        "name = Kinds import only to the left (contracts, modules, features, services, apps)",
        "type = layers",
        "layers =",
    ]
    for kind in reversed(KIND_ORDER):
        group = [mods[k] for k in keys if layout[k]["kind"] == kind]
        if group:
            lines.append("    " + " | ".join(group))
    for key in keys:
        allowed = set(layout[key]["deps"])
        banned = [mods[k] for k in keys if k != key and k not in allowed]
        if not banned:
            continue
        lines += [
            "",
            f"[importlinter:contract:deps-{key}]",
            f"name = {key} imports only its declared deps",
            "type = forbidden",
            f"source_modules = {mods[key]}",
            "forbidden_modules =",
            *[f"    {m}" for m in banned],
            "allow_indirect_imports = True",
        ]
    for key in keys:
        private = _private_modules(layout, key, root)
        others = [mods[k] for k in keys if k != key]
        if not private or not others:
            continue
        lines += [
            "",
            f"[importlinter:contract:private-{key}]",
            f"name = Nobody reaches into the private modules of {key}",
            "type = forbidden",
            "source_modules =",
            *[f"    {m}" for m in others],
            "forbidden_modules =",
            *[f"    {p}" for p in private],
            "allow_indirect_imports = True",
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    layout = load_layout()
    if "--write-importlinter" in argv:
        (ROOT / ".importlinter").write_text(importlinter_config(layout))
        print("wrote .importlinter", file=sys.stderr)
    problems = check(layout)
    for p in problems:
        print(p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
